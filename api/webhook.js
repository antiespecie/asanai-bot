async function handleStart(chatId, firstName) {
  const user = getUser(chatId);
  const name = firstName || "friend";

  if (!user.lang) {
    await sendMessage(chatId, `🌐 Welcome to Asanai!\n\nBienvenido a Asanai!\n\nChoose your language / Elige tu idioma:`, { reply_markup: langMenu() });
    return;
  }

  await sendMessage(chatId, t(user).welcome(name), { reply_markup: mainMenu(user) });
}

async function handleCallback(query) {
  const chatId = query.message.chat.id;
  const msgId = query.message.message_id;
  const data = query.data;
  const user = getUser(chatId);
  const pro = isProActive(user);
  const tx = t(user);

  await callTelegram("answerCallbackQuery", { callback_query_id: query.id });

  // Language selection
  if (data === "menu_lang") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.changeLang, parse_mode: "HTML", reply_markup: langMenu() });
    return;
  }

  if (data === "lang_en" || data === "lang_es") {
    user.lang = data === "lang_en" ? "en" : "es";
    const firstName = query.from?.first_name || "friend";
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: t(user).welcome(firstName), parse_mode: "HTML", reply_markup: mainMenu(user) });
    return;
  }

  if (data === "back_main") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: user.lang === "es" ? "¿Qué te gustaría hacer hoy?" : "What would you like to do today?", parse_mode: "HTML", reply_markup: mainMenu(user) });
    return;
  }

  if (data === "menu_plan") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.chooseGoal, parse_mode: "HTML", reply_markup: goalMenu(user) });
    return;
  }

  if (data.startsWith("plan_")) {
    const goal = data.replace("plan_", "");
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.generating, parse_mode: "HTML" });
    try {
      const raw = await generateYogaPlan(goal, user.lang);
      const formatted = formatPlan(raw, user.lang);
      updateStreak(user);
      await callTelegram("editMessageText", {
        chat_id: chatId, message_id: msgId,
        text: formatted + tx.streakLabel(user.streak, user.sessions),
        parse_mode: "HTML",
        reply_markup: { inline_keyboard: [[{ text: tx.differentGoal, callback_data: "menu_plan" }], [{ text: tx.home, callback_data: "back_main" }]] },
      });
    } catch (err) {
      await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.error, parse_mode: "HTML", reply_markup: { inline_keyboard: [[{ text: tx.back, callback_data: "menu_plan" }]] } });
    }
    return;
  }

  if (data === "menu_classes") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: pro ? tx.classesTextPro : tx.classesTextFree, parse_mode: "HTML", reply_markup: classesMenu(user) });
    return;
  }

  if (data.startsWith("class_") && data !== "class_locked") {
    const info = getClassInfo(data, user.lang);
    if (info) {
      await callTelegram("editMessageText", {
        chat_id: chatId, message_id: msgId,
        text: `<b>${info.title}</b>\n\n${info.body}`,
        parse_mode: "HTML",
        reply_markup: { inline_keyboard: [[{ text: tx.startSession, callback_data: "class_done" }], [{ text: tx.allClasses, callback_data: "menu_classes" }]] },
      });
    }
    return;
  }

  if (data === "class_done") {
    updateStreak(user);
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.sessionDone(user.streak, user.sessions), parse_mode: "HTML", reply_markup: { inline_keyboard: [[{ text: tx.home, callback_data: "back_main" }]] } });
    return;
  }

  if (data === "class_locked") {
    await callTelegram("editMessageText", {
      chat_id: chatId, message_id: msgId,
      text: tx.classLocked, parse_mode: "HTML",
      reply_markup: { inline_keyboard: [[{ text: tx.upgradeBtn, callback_data: "menu_upgrade" }], [{ text: tx.allClasses, callback_data: "menu_classes" }]] },
    });
    return;
  }

  if (data === "menu_streak") {
    await callTelegram("editMessageText", {
      chat_id: chatId, message_id: msgId,
      text: tx.streakMsg(user, pro), parse_mode: "HTML",
      reply_markup: { inline_keyboard: [[{ text: tx.startNewSession, callback_data: "menu_plan" }], [{ text: tx.home, callback_data: "back_main" }]] },
    });
    return;
  }

  if (data === "menu_upgrade") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.upgradeText, parse_mode: "HTML", reply_markup: { inline_keyboard: [[{ text: tx.subscribeBtn, callback_data: "do_upgrade" }], [{ text: tx.back, callback_data: "back_main" }]] } });
    return;
  }

  if (data === "do_upgrade") {
    await callTelegram("sendInvoice", {
      chat_id: chatId, title: "Asanai Pro", description: user.lang === "es" ? "Clases ilimitadas + coaching IA. Cancela cuando quieras." : "Unlimited classes + AI coaching. Cancel anytime.",
      payload: "pro_weekly", currency: "XTR",
      prices: [{ label: user.lang === "es" ? "Membresía semanal Pro" : "Pro weekly membership", amount: 299 }],
    });
    return;
  }

  if (data === "menu_profile") {
    await callTelegram("editMessageText", { chat_id: chatId, message_id: msgId, text: tx.proActive(new Date(user.proExpiry).toLocaleDateString()), parse_mode: "HTML", reply_markup: { inline_keyboard: [[{ text: tx.home, callback_data: "back_main" }]] } });
    return;
  }
}

async function handlePayment(msg) {
  const chatId = msg.chat.id;
  const user = getUser(chatId);
  user.isPro = true;
  user.proExpiry = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString();
  await sendMessage(chatId, t(user).paymentSuccess(new Date(user.proExpiry).toLocaleDateString()), { reply_markup: mainMenu(user) });
}

