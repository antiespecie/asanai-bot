// Vercel handler
// ---------------------------------------------------------------------------
module.exports = async function handler(req, res) {
  if (req.method === "GET") return res.status(200).json({ ok: true, app: "Asanai", status: "running" });
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  try {
    const update = req.body;

    if (update.message) {
      const msg = update.message;
      const chatId = msg.chat.id;
      const text = msg.text || "";
      const firstName = msg.from?.first_name;
      const user = getUser(chatId);

      if (msg.successful_payment) {
        await handlePayment(msg);
      } else if (text === "/start") {
        await handleStart(chatId, firstName);
      } else if (text === "/lang") {
        await sendMessage(chatId, t(user).changeLang, { reply_markup: langMenu() });
      } else if (text === "/plan") {
        await sendMessage(chatId, t(user).chooseGoal, { reply_markup: goalMenu(user) });
      } else if (text === "/classes") {
        await sendMessage(chatId, isProActive(user) ? t(user).classesTextPro : t(user).classesTextFree, { reply_markup: classesMenu(user) });
      } else if (text === "/streak") {
        await sendMessage(chatId, t(user).streakMsg(user, isProActive(user)));
      } else if (text === "/upgrade") {
        await sendMessage(chatId, t(user).upgradeText, { reply_markup: { inline_keyboard: [[{ text: t(user).subscribeBtn, callback_data: "do_upgrade" }]] } });
      } else if (text === "/help") {
        await sendMessage(chatId, user.lang === "es"
          ? `/start — menú principal\n/plan — obtener plan de yoga\n/classes — explorar clases\n/streak — ver tu progreso\n/upgrade — ir a Pro\n/lang — cambiar idioma`
          : `/start — main menu\n/plan — get a yoga plan\n/classes — browse classes\n/streak — see progress\n/upgrade — go Pro\n/lang — change language`);
      } else {
        await handleStart(chatId, firstName);
      }
    }

    if (update.callback_query) await handleCallback(update.callback_query);
    if (update.pre_checkout_query) await callTelegram("answerPreCheckoutQuery", { pre_checkout_query_id: update.pre_checkout_query.id, ok: true });

    res.status(200).json({ ok: true });
  } catch (err) {
    console.error("Webhook error:", err);
    res.status(200).json({ ok: true });
  }
};
