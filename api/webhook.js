async function generateYogaPlan(goal, lang) {
  const goals = {
    relax: { en: "gentle stretching and relaxation, releasing tension", es: "estiramiento suave y relajación, liberando tensión" },
    energize: { en: "energizing morning flow with dynamic sun salutations", es: "flujo matutino energizante con saludos al sol dinámicos" },
    backpain: { en: "lower back pain relief and core strengthening", es: "alivio del dolor de espalda baja y fortalecimiento del núcleo" },
    sleep: { en: "bedtime wind-down with calming breathwork", es: "relajación nocturna con respiración calmante" },
    core: { en: "core strength and stability building", es: "construcción de fuerza y estabilidad del núcleo" },
    flexible: { en: "deep flexibility and hip opening", es: "flexibilidad profunda y apertura de caderas" },
  };

  const focus = goals[goal]?.[lang] || goals.relax.en;
  const isEs = lang === "es";

  const prompt = isEs
    ? `Eres Asanai, un coach de yoga con IA. Crea un plan de sesión de yoga corto y amigable para alguien que quiere: ${focus}. Nivel: principiante.

Responde en este formato exacto:
TITULO: [nombre de la sesión]
DURACION: [X min]
DESCRIPCION: [máximo 2 oraciones, cálidas y motivadoras]
POSTURAS:
1. [Nombre de postura] — [duración] — [beneficio en una línea]
2. [Nombre de postura] — [duración] — [beneficio en una línea]
3. [Nombre de postura] — [duración] — [beneficio en una línea]
4. [Nombre de postura] — [duración] — [beneficio en una línea]
5. [Nombre de postura] — [duración] — [beneficio en una línea]
CONSEJO: [un consejo práctico para la sesión de hoy]

Mantén un tono cálido, alentador y simple. Sin markdown, solo texto plano.`
    : `You are Asanai, an AI yoga coach. Create a short friendly yoga session plan for someone who wants: ${focus}. Level: beginner.

Respond in this exact format:
TITLE: [session name]
DURATION: [X min]
DESCRIPTION: [2 sentences max, warm and motivating]
POSES:
1. [Pose name] — [duration] — [one-line benefit]
2. [Pose name] — [duration] — [one-line benefit]
3. [Pose name] — [duration] — [one-line benefit]
4. [Pose name] — [duration] — [one-line benefit]
5. [Pose name] — [duration] — [one-line benefit]
TIP: [one practical tip for today's session]

Keep it warm, encouraging, and simple. No markdown, just plain text.`;

  const msg = await anthropic.messages.create({
    model: "claude-sonnet-4-6",
    max_tokens: 1000,
    messages: [{ role: "user", content: prompt }],
  });

  return msg.content[0].text;
}

function formatPlan(raw, lang) {
  const isEs = lang === "es";
  const lines = raw.split("\n").filter((l) => l.trim());
  let out = isEs ? "🧘 <b>Tu Sesión Asanai</b>\n\n" : "🧘 <b>Your Asanai Session</b>\n\n";

  for (const line of lines) {
    const key = isEs ? ["TITULO:", "DURACION:", "DESCRIPCION:", "POSTURAS:", "CONSEJO:"] : ["TITLE:", "DURATION:", "DESCRIPTION:", "POSES:", "TIP:"];
    if (line.startsWith(key[0])) out += `<b>${line.replace(key[0], "").trim()}</b>\n`;
    else if (line.startsWith(key[1])) out += `⏱ ${line.replace(key[1], "").trim()}\n\n`;
    else if (line.startsWith(key[2])) out += `${line.replace(key[2], "").trim()}\n\n`;
    else if (line.startsWith(key[3])) out += `<b>${isEs ? "Tus posturas:" : "Your poses:"}</b>\n`;
    else if (/^\d\./.test(line)) out += `${line}\n`;
    else if (line.startsWith(key[4])) out += `\n💡 <i>${line.replace(key[4], "").trim()}</i>`;
  }
  return out;
}

